import sys
sys.path.insert(0, sys.argv[1])
import qrcode
url, out = sys.argv[2], sys.argv[3]
q = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=0)
q.add_data(url); q.make(fit=True)
m = q.get_matrix()
n = len(m); pad = 4; size = n + 2 * pad
parts = []
for y, row in enumerate(m):
    x = 0
    while x < n:
        if row[x]:
            s = x
            while x < n and row[x]: x += 1
            parts.append(f"M{s+pad},{y+pad}h{x-s}v1h-{x-s}z")
        else:
            x += 1
xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- QR code for {url} (version {q.version}, error correction M), generated by tools/qr/qr_vector.py. Always dark on white. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size*6}dp" android:height="{size*6}dp" android:viewportWidth="{size}" android:viewportHeight="{size}">
    <path android:fillColor="#FFFFFFFF" android:pathData="M0,0h{size}v{size}h-{size}z" />
    <path android:fillColor="#FF000000" android:pathData="{''.join(parts)}" />
</vector>
'''
open(out, "w").write(xml)
print("modules", n, "version", q.version, "bytes", len(xml))
