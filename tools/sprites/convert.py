#!/usr/bin/env python3
"""
Converts the owner's character sprites (PNG 512x512, transparent) into lossless WebP resources
and measures them for the renderer. Run from the repository root:

    python3 -I tools/sprites/convert.py <folder with iskra_<name>_512.png>

Writes:
  app/src/main/res/drawable-nodpi/iskra_<name>.webp   lossless, pixels checked after encoding
  core/src/main/kotlin/ru/iskra/core/avatar/SpriteAtlas.kt   measured metrics (generated)

Metrics per sprite, in source pixels:
  feetY   lowest opaque row (alignment by the feet)
  anchorX horizontal centre of the head (middle between the ear tips): the bodies are not
          centred in their pictures, and the tail would skew a bounding-box centre
  head    distance between the ear tips; the renderer scales each sprite so that the head
          matches the "stand" head (sit and sleep are drawn at their own scale)
Requires Pillow with WebP support.
"""
import glob, math, os, re, sys
from PIL import Image

NAMES = ["stand", "sit", "sleep", "walk_01", "walk_02", "wave", "phone",
         "joy", "sad", "angry", "surprise", "shy", "thoughtful", "sleepy", "sly"]
# In "sleep" the head lies on its side and one ear points left, so the automatic search finds
# only one tip. Points measured by hand on the 512 px picture.
EAR_OVERRIDE = {"sleep": [(28, 150), (273, 65)]}
ALPHA = 128

def ear_tips(a, w, h):
    px = a.load()
    top = []
    for x in range(w):
        y = next((y for y in range(h) if px[x, y] > ALPHA), None)
        top.append(h if y is None else y)
    peaks = []
    for x in range(w):
        y = top[x]
        if y >= h or y != min(top[max(0, x - 25):x + 26]):
            continue
        left = max(top[max(0, x - 70):x] or [h]); right = max(top[x + 1:x + 71] or [h])
        if left - y >= 20 and right - y >= 20 and not (peaks and x - peaks[-1][0] < 30):
            peaks.append((x, y))
    return peaks

def main(src):
    root = os.getcwd()
    res = os.path.join(root, "app/src/main/res/drawable-nodpi")
    os.makedirs(res, exist_ok=True)
    rows = []
    for name in NAMES:
        path = os.path.join(src, f"iskra_{name}_512.png")
        im = Image.open(path).convert("RGBA")
        w, h = im.size
        assert (w, h) == (512, 512), f"{name}: {w}x{h}, expected 512x512"
        a = im.getchannel("A")
        bbox = a.point(lambda v: 255 if v > ALPHA else 0).getbbox()
        assert bbox and im.getpixel((0, 0))[3] == 0, f"{name}: no transparent background"
        tips = EAR_OVERRIDE.get(name) or ear_tips(a, w, h)
        assert len(tips) == 2, f"{name}: ear tips {tips}"
        (x1, y1), (x2, y2) = tips
        head = math.hypot(x2 - x1, y2 - y1)
        anchor = (bbox[0] + bbox[2]) / 2 if name == "sleep" else (x1 + x2) / 2
        out = os.path.join(res, f"iskra_{name}.webp")
        im.save(out, "WEBP", lossless=True, quality=100, method=6)
        back = Image.open(out).convert("RGBA")
        # Lossless check: every visible pixel identical (colour under alpha 0 may be dropped).
        a1, a2 = im.tobytes(), back.tobytes()
        diff = sum(1 for i in range(0, len(a1), 4) if a1[i:i + 4] != a2[i:i + 4] and not (a1[i + 3] == 0 and a2[i + 3] == 0))
        assert diff == 0, f"{name}: {diff} pixels changed"
        rows.append((name, bbox[3], anchor, head, bbox, os.path.getsize(path), os.path.getsize(out)))
        print(f"{name:11s} bbox={bbox} feet={bbox[3]} anchorX={anchor:.1f} head={head:.1f} "
              f"png={os.path.getsize(path)//1024}K webp={os.path.getsize(out)//1024}K")

    kt = os.path.join(root, "core/src/main/kotlin/ru/iskra/core/avatar/SpriteAtlas.kt")
    lines = [
        "// GENERATED by tools/sprites/convert.py from the owner's 512x512 sprites. Do not edit by hand.",
        "package ru.iskra.core.avatar",
        "",
        "/**",
        " * The character's sprites (app resources `drawable-nodpi/iskra_<file>.webp`) with metrics measured",
        " * on the pictures, in source pixels: [feetY] lowest opaque row, [anchorX] head centre, [head] ear-tip distance,",
        " * [top]/[left]/[right] the opaque bounds.",
        " */",
        "enum class Sprite(val file: String, val feetY: Float, val anchorX: Float, val head: Float, val top: Float, val left: Float, val right: Float) {",
    ]
    for (name, feet, anchor, head, bbox, _, _) in rows:
        ident = re.sub(r"_(\d+)", r"\1", name).upper()
        lines.append(f'    {ident}("{name}", {feet}f, {anchor:.1f}f, {head:.1f}f, {bbox[1]}f, {bbox[0]}f, {bbox[2]}f),')
    lines[-1] = lines[-1][:-1] + ";"
    lines += ["", "    companion object { const val SIZE = 512f }", "}", ""]
    with open(kt, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote", kt)

if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
